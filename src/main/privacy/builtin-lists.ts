export const BUILTIN_AD_HOSTS: readonly string[] = AD_HOSTS
export const BUILTIN_TRACKER_HOSTS: readonly string[] = TRACKER_HOSTS

export function builtinRules(): string[] {
  const rules: string[] = []
  for (const host of AD_HOSTS) {
    rules.push(`||${host}^`)
  }
  for (const host of TRACKER_HOSTS) {
    rules.push(`||${host}^`)
  }
  for (const path of PATH_RULES) {
    rules.push(`*${path}*`)
  }
  return rules
}

